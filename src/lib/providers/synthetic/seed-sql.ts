import type { Fragrance } from "@/types/fragrance";
import { NOTES } from "@/lib/fragrance/notes";
import { slugify } from "@/lib/fragrance/utils";
import { BRANDS } from "./archetypes";
import { stableUuid } from "./generator";

/** Builds an idempotent SQL seed (upserts) for the synthetic catalog. */

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (items: string[]) => `array[${items.map(q).join(",")}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

export function buildSeedSql(catalog: Fragrance[]): string {
  const lines: string[] = [
    "-- Generated by scripts/generate-synthetic-data.ts. Do not edit by hand.",
    "-- All brands, products and prices below are FICTIONAL demonstration data.",
    "begin;",
    "",
    `insert into public.data_sources (id, name, kind, license, attribution, is_active)
values ('synthetic', 'Scentify Synthetic Dataset', 'catalog', 'CC0-1.0 (generated)', 'Scentify synthetic demonstration dataset', true)
on conflict (id) do update set name = excluded.name, updated_at = now();`,
    "",
  ];

  lines.push("insert into public.notes (id, name, note_group, secondary_group, aliases, warmth, intensity) values");
  lines.push(
    NOTES.map(
      (n) =>
        `  (${q(n.id)}, ${q(n.name)}, ${q(n.groups[0])}, ${q(n.groups[1] ?? null)}, ${arr(n.aliases ?? [])}, ${n.warmth}, ${n.intensity})`,
    ).join(",\n") +
      "\non conflict (id) do update set name = excluded.name, note_group = excluded.note_group, secondary_group = excluded.secondary_group, aliases = excluded.aliases, warmth = excluded.warmth, intensity = excluded.intensity;",
  );
  lines.push("");

  lines.push("insert into public.brands (id, slug, name, tier, is_synthetic, source_id) values");
  lines.push(
    BRANDS.map((b) => {
      const slug = slugify(b.name);
      return `  (${q(stableUuid(`brand:${slug}`))}, ${q(slug)}, ${q(b.name)}, ${q(b.tier)}, true, 'synthetic')`;
    }).join(",\n") + "\non conflict (slug) do update set name = excluded.name, tier = excluded.tier;",
  );
  lines.push("");

  for (const f of catalog) {
    const brandId = stableUuid(`brand:${f.brandSlug}`);
    lines.push(
      `insert into public.fragrances (id, slug, name, brand_id, concentration, gender, release_year, description, families, accords, longevity, projection, versatility, rating, popularity, visual, image_url, is_synthetic, source_id, source_record_id, attribution, license, dedupe_key, source_updated_at, time_day, time_night)
values (${q(f.id)}, ${q(f.slug)}, ${q(f.name)}, ${q(brandId)}, ${q(f.concentration)}, ${q(f.gender)}, ${f.releaseYear}, ${q(f.description)}, ${arr(f.families)}, ${json(f.accords)}, ${f.longevity}, ${f.projection}, ${f.versatility}, ${f.rating}, ${f.popularity}, ${json(f.visual)}, null, true, 'synthetic', ${q(f.source.providerRecordId)}, ${q(f.source.attribution)}, ${q(f.source.license)}, ${q(`${f.brandSlug}|${slugify(f.name)}|${f.concentration.toLowerCase()}`)}, ${q(f.source.lastUpdated)}, ${f.timeOfDay.day}, ${f.timeOfDay.night})
on conflict (id) do update set name = excluded.name, description = excluded.description, families = excluded.families, accords = excluded.accords, longevity = excluded.longevity, projection = excluded.projection, versatility = excluded.versatility, rating = excluded.rating, popularity = excluded.popularity, visual = excluded.visual, source_updated_at = excluded.source_updated_at, time_day = excluded.time_day, time_night = excluded.time_night, updated_at = now();`,
    );
    lines.push(`delete from public.fragrance_notes where fragrance_id = ${q(f.id)};`);
    const noteRows = (["top", "middle", "base"] as const).flatMap((tier) =>
      f.notes[tier].map((id, i) => `(${q(f.id)}, ${q(id)}, ${q(tier)}, ${i})`),
    );
    lines.push(`insert into public.fragrance_notes (fragrance_id, note_id, tier, position) values ${noteRows.join(", ")};`);
    const a = f.attributes;
    lines.push(
      `insert into public.fragrance_attributes (fragrance_id, freshness, sweetness, woodiness, spiciness, warmth, floralness, fruitiness, greenness, smokiness, creaminess, powderiness, muskiness, season_spring, season_summer, season_autumn, season_winter, occasion_work, occasion_school, occasion_date, occasion_casual, occasion_formal, occasion_gym, occasion_night_out)
values (${q(f.id)}, ${a.freshness}, ${a.sweetness}, ${a.woodiness}, ${a.spiciness}, ${a.warmth}, ${a.floralness}, ${a.fruitiness}, ${a.greenness}, ${a.smokiness}, ${a.creaminess}, ${a.powderiness}, ${a.muskiness}, ${f.seasons.spring}, ${f.seasons.summer}, ${f.seasons.autumn}, ${f.seasons.winter}, ${f.occasions.work}, ${f.occasions.school}, ${f.occasions.date}, ${f.occasions.casual}, ${f.occasions.formal}, ${f.occasions.gym}, ${f.occasions.night_out})
on conflict (fragrance_id) do update set freshness = excluded.freshness, sweetness = excluded.sweetness, woodiness = excluded.woodiness, spiciness = excluded.spiciness, warmth = excluded.warmth, floralness = excluded.floralness, fruitiness = excluded.fruitiness, greenness = excluded.greenness, smokiness = excluded.smokiness, creaminess = excluded.creaminess, powderiness = excluded.powderiness, muskiness = excluded.muskiness, season_spring = excluded.season_spring, season_summer = excluded.season_summer, season_autumn = excluded.season_autumn, season_winter = excluded.season_winter, occasion_work = excluded.occasion_work, occasion_school = excluded.occasion_school, occasion_date = excluded.occasion_date, occasion_casual = excluded.occasion_casual, occasion_formal = excluded.occasion_formal, occasion_gym = excluded.occasion_gym, occasion_night_out = excluded.occasion_night_out, updated_at = now();`,
    );
    const variantRows = f.variants.map(
      (v) => `(${q(v.id)}, ${q(f.id)}, ${v.sizeMl}, ${v.price}, ${q(v.currency)}, true)`,
    );
    lines.push(
      `insert into public.fragrance_variants (id, fragrance_id, size_ml, list_price, currency, is_synthetic) values ${variantRows.join(", ")}
on conflict (id) do update set list_price = excluded.list_price, updated_at = now();`,
    );
    lines.push("");
  }

  lines.push("delete from public.fragrance_related where source = 'synthetic';");
  const related = catalog.flatMap((f) =>
    f.relatedIds.map((rid, i) => `(${q(f.id)}, ${q(rid)}, ${i}, 'synthetic')`),
  );
  lines.push(`insert into public.fragrance_related (fragrance_id, related_id, rank, source) values\n  ${related.join(",\n  ")};`);
  lines.push("", "commit;", "");
  return lines.join("\n");
}
