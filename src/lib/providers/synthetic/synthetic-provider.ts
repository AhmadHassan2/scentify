import type { Fragrance } from "@/types/fragrance";
import type { FragranceDataProvider, ProviderMetadata } from "../types";
import catalogJson from "./synthetic-fragrances.json";

/**
 * Serves the bundled, pre-generated synthetic catalog.
 * Regenerate with `npm run data:generate`.
 */
export class SyntheticFragranceProvider implements FragranceDataProvider {
  readonly metadata: ProviderMetadata = {
    id: "synthetic",
    name: "Scentify Synthetic Dataset",
    kind: "catalog",
    license: "CC0-1.0 (generated by Scentify)",
    attribution: "Scentify synthetic demonstration dataset — fictional brands, products and prices",
    homepage: null,
    commercialUseVerified: true,
    rateLimitPerMinute: Number.POSITIVE_INFINITY,
  };

  private readonly records = catalogJson as unknown as Fragrance[];

  async getFragrances(): Promise<Fragrance[]> {
    return this.records;
  }

  async getFragranceById(id: string): Promise<Fragrance | null> {
    return this.records.find((f) => f.id === id || f.source.providerRecordId === id) ?? null;
  }

  async getUpdatedFragrances(since: Date): Promise<Fragrance[]> {
    return this.records.filter((f) => new Date(f.source.lastUpdated) > since);
  }
}
